// Client-side checks for instant form feedback. The Rust backend
// re-validates everything and is the authority; keep these rules aligned
// with recovery-service/src/validation.rs.

// eslint-disable-next-line no-control-regex
const CONTROL = /[\u0000-\u001f\u007f-\u009f]/;
// eslint-disable-next-line no-control-regex
const CONTROL_EXCEPT_WS = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f-\u009f]/;

export function validateSingleLine(label: string, v: string, max: number, required: boolean): string | null {
  const t = v.trim();
  if (required && !t) return `${label} is required`;
  if ([...t].length > max) return `${label} must be at most ${max} characters`;
  if (CONTROL.test(t)) return `${label} contains invalid characters`;
  return null;
}

export function validateMultiLine(label: string, v: string, max: number): string | null {
  const t = v.trim();
  if ([...t].length > max) return `${label} must be at most ${max} characters`;
  if (CONTROL_EXCEPT_WS.test(t)) return `${label} contains invalid characters`;
  return null;
}

export function validateCaseNumber(v: string): string | null {
  const t = v.trim().toUpperCase();
  if (!t) return null; // optional: generated by the backend
  return /^[A-Z0-9][A-Z0-9-]{2,31}$/.test(t)
    ? null
    : "3–32 characters: letters, digits and hyphens, starting with a letter or digit";
}
